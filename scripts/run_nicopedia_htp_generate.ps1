# Nicopedia byte-level HTP generation runner.
#
# Stages the HTP-trained private checkpoint (build/reports/nicopedia-htp-training)
# and an arbitrary Japanese prompt (UTF-8 bytes) into the app-private files
# directory, then drives QNN_HTP_TINY_LANGUAGE_MODEL_NICOPEDIA_GENERATE.
# The device runs the full autoregressive loop (fixed-prefix CPU/HTP parity,
# 8-step AR parity, then greedy/sampled generation) on the HTP graph; only
# generated private bytes (hex) plus aggregate metrics return in the report.
#
# The prompt text and the generated bytes NEVER enter public artifacts or the
# private state dir (only counts and SHA-256 fingerprints do).  Terminal
# output may show the lossless \xNN-escaped display.
param(
    [string]$Model = '',                 # L6 | L19 (required)
    [int]$Seed = 0,                      # L6: 1/2/4, L19: 1
    [string]$Prompt = '',                # arbitrary Japanese text
    [string]$PromptFile = '',            # alternative: raw UTF-8 bytes file
    [int]$MaxNewBytes = 64,              # 1..1024
    [string]$Mode = 'Greedy',            # Greedy | Sample
    [double]$Temperature = 1.0,
    [int]$TopK = 256,
    [uint32]$SamplingSeed = 0,
    [string]$QairtSdkRoot = '',
    [string]$ExpectedBuildId = '',
    [switch]$SkipBuild,
    [switch]$SkipInstall,
    [int]$PollLimit = 600,
    [int]$CheckpointStep = 320,
    [string]$GatePolicy = 'legacy',   # legacy | candidate (protocol F)
    [switch]$CandidatePolicyApproved, # required to run -GatePolicy candidate
    [switch]$AuditOnly,               # accept a FAILED gate report (audit runs)
    [int]$HtpGraphPrecisionMode = 0,  # private diagnostics: 0 unset, 1 fp16, 2 fp32
    [int]$HtpGraphPrecisionCompensation = 0,  # private diagnostics: 0 unset, 1 false, 2 true
    [int]$HtpGraphWeightsPacking = 0,  # private diagnostics: 0 unset, 1 false, 2 true
    [int]$HtpGraphAdvancedActivationFusion = 0,  # private diagnostics: 0 unset, 1 false, 2 true
    [switch]$HtpNativeTensorFp16,  # private diagnostics: declare NATIVE tensors FP16
    [switch]$SelfTest
)

