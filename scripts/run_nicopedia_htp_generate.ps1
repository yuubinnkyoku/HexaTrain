function Write-Event([string]$Type, [hashtable]$Fields) {
    $entry = @{ ts = [DateTimeOffset]::UtcNow.ToString('o'); type = $Type } + $Fields
    Add-Content -LiteralPath (Join-Path $stateDir 'events.jsonl') `
        -Value ($entry | ConvertTo-Json -Compress) -Encoding utf8
}

function Get-Sha256Hex([string]$LiteralPath) {
    $hash = Get-FileHash -LiteralPath $LiteralPath -Algorithm SHA256
    return $hash.Hash.ToLowerInvariant()
}

# Lossless UTF-8 display: valid sequences pass through, invalid/truncated
# bytes become \xNN escapes (lowercase).  Mirrors nicopedia_generation.h.
function Get-SafeUtf8Display([byte[]]$Bytes) {
    $out = [System.Text.StringBuilder]::new()
    $pos = 0
    while ($pos -lt $Bytes.Length) {
        $b = $Bytes[$pos]
        $length = 0
        if ($b -lt 0x80) {
            $length = 1
        } elseif ($b -ge 0xC2 -and $b -le 0xDF) {
            $length = 2
        } elseif ($b -ge 0xE0 -and $b -le 0xEF) {
            $length = 3
        } elseif ($b -ge 0xF0 -and $b -le 0xF4) {
            $length = 4
        }
        $valid = $true
        if ($length -gt 0 -and $pos + $length -le $Bytes.Length) {
            for ($i = 1; $i -lt $length; $i++) {
                $c = $Bytes[$pos + $i]
                if ($c -lt 0x80 -or $c -gt 0xBF) { $valid = $false; break }
            }
            if ($length -eq 3 -and $b -eq 0xE0 -and $Bytes[$pos + 1] -lt 0xA0) { $valid = $false }
            if ($length -eq 3 -and $b -eq 0xED -and $Bytes[$pos + 1] -ge 0xA0) { $valid = $false }
            if ($length -eq 4 -and $b -eq 0xF0 -and $Bytes[$pos + 1] -lt 0x90) { $valid = $false }
            if ($length -eq 4 -and $b -eq 0xF4 -and $Bytes[$pos + 1] -ge 0x90) { $valid = $false }
        } else {
            $valid = $false
        }
        if ($valid) {
            [void]$out.Append([System.Text.Encoding]::UTF8.GetString($Bytes, $pos, $length))
            $pos += $length
        } else {
            [void]$out.Append('\x')
            [void]$out.Append($b.ToString('x2'))
            $pos += 1
        }
    }
    return $out.ToString()
}

function Invoke-SelfTest {
    # Safe display mirrors the C++ core (lossless \xNN escapes).
    $cases = @(
        @{ Bytes = [byte[]](0x68, 0x69); Expect = 'hi' },
        @{ Bytes = [byte[]](0xE3, 0x81, 0x93); Expect = [string][char]0x3053 },
        @{ Bytes = [byte[]](0xE3, 0x81); Expect = '\xe3\x81' },
        @{ Bytes = [byte[]](0x61, 0xFF, 0x80, 0x62); Expect = 'a\xff\x80b' },
        @{ Bytes = [byte[]](0xED, 0xA0, 0x80); Expect = '\xed\xa0\x80' }
    )
    foreach ($case in $cases) {
        $actual = Get-SafeUtf8Display -Bytes $case.Bytes
        if ($actual -ne $case.Expect) { throw "SELFTEST_DISPLAY: '$actual' != '$($case.Expect)'" }
    }
    $empty = Get-SafeUtf8Display -Bytes ([byte[]]@())
    if ($empty -ne '') { throw 'SELFTEST_DISPLAY_EMPTY' }

    # CheckpointStep file-name resolution mirrors the device-side
    # nprtParseCheckpointStep contract (htp-seed<S>-l<L>-step<N>.ckpt).
    $ckRoot = Join-Path $env:TEMP ("nicopedia-gen-selftest-" + [guid]::NewGuid().ToString('N'))
    [IO.Directory]::CreateDirectory($ckRoot) | Out-Null
    try {
        $step320Ckpt = Join-Path $ckRoot 'htp-seed1-l19-step320.ckpt'
        $step1000Ckpt = Join-Path $ckRoot 'htp-seed1-l19-step1000.ckpt'
        [IO.File]::WriteAllText($step320Ckpt, 'selftest-320')
        [IO.File]::WriteAllText($step1000Ckpt, 'selftest-1000')
        $anchor320 = Join-Path $ckRoot 'seed1-l19-steps320-result.txt'
        $anchor1000 = Join-Path $ckRoot 'seed1-l19-steps1000-result.txt'
        [IO.File]::WriteAllText($anchor320, "final_parameter_hash=fnv1a64:0123456789abcdef`n")
        [IO.File]::WriteAllText($anchor1000, "final_parameter_hash=fnv1a64:fedcba9876543210`n")
        # Resolve-* helpers must pick the step-driven file names.
        $checkpoint = Join-Path $ckRoot "htp-seed1-l19-step320.ckpt"
        $anchorFile = Join-Path $ckRoot "seed1-l19-steps320-result.txt"
        if (-not (Test-Path -LiteralPath $checkpoint -PathType Leaf) -or
            -not (Test-Path -LiteralPath $anchorFile -PathType Leaf)) {
            throw 'SELFTEST_CHECKPOINT_STEP_320'
        }
        $checkpoint1000 = Join-Path $ckRoot "htp-seed1-l19-step1000.ckpt"
        if (-not (Test-Path -LiteralPath $checkpoint1000 -PathType Leaf) -or
            -not (Test-Path -LiteralPath $anchor1000 -PathType Leaf)) {
            throw 'SELFTEST_CHECKPOINT_STEP_1000'
        }
        # A missing step-N file must fail closed.
        foreach ($missing in @(
                (Join-Path $ckRoot 'htp-seed1-l19-step999999.ckpt'),
                (Join-Path $ckRoot 'htp-seed1-l19-step0.ckpt'))) {
            if (Test-Path -LiteralPath $missing -PathType Leaf) {
                throw 'SELFTEST_CHECKPOINT_STEP_LEAK'
            }
        }
    } finally {
        [IO.Directory]::Delete($ckRoot, $true)
    }

    # Aggregate metrics mirror nicopedia_generation.h GenerationAggregates;
    # the shared helper owns both the implementation and its self-test.
    Test-GenerationAggregateSelfTest

    # SHA-256 fingerprint plumbing.
    $temp = Join-Path $env:TEMP ("nicopedia-gen-selftest-" + [guid]::NewGuid().ToString('N'))
    [IO.Directory]::CreateDirectory($temp) | Out-Null
    try {
        $sample = Join-Path $temp 'prompt.bin'
        [IO.File]::WriteAllBytes($sample, [byte[]](0xE3, 0x81, 0x93))
        $h1 = Get-Sha256Hex $sample
        $h2 = Get-Sha256Hex $sample
        if ($h1 -ne $h2 -or $h1.Length -ne 64) { throw 'SELFTEST_SHA256' }
    } finally {
        [IO.Directory]::Delete($temp, $true)
    }

    # CheckpointStep range gate (mirrors the parameter validation).
    foreach ($bad in @(0, -1, 1000000, 9999999)) {
        if ($bad -ge 1 -and $bad -le 999999) { throw "SELFTEST_CHECKPOINT_STEP_RANGE: $bad" }
    }
    if (-not (320 -ge 1 -and 320 -le 999999)) { throw 'SELFTEST_CHECKPOINT_STEP_320_RANGE' }
    if (-not (1000 -ge 1 -and 1000 -le 999999)) { throw 'SELFTEST_CHECKPOINT_STEP_1000_RANGE' }

    # HTP graph precision diagnostic switch range gate (0=unset, 1=fp16, 2=fp32).
    foreach ($bad in @(-1, 3, 99)) {
        if ($bad -ge 0 -and $bad -le 2) { throw "SELFTEST_HTP_GRAPH_PRECISION_RANGE: $bad" }
    }
    foreach ($bad in @(-1, 3, 99)) {
        if ($bad -ge 0 -and $bad -le 2) { throw "SELFTEST_HTP_GRAPH_PRECISION_COMPENSATION_RANGE: $bad" }
    }
    foreach ($bad in @(-1, 3, 99)) {
        if ($bad -ge 0 -and $bad -le 2) { throw "SELFTEST_HTP_GRAPH_WEIGHTS_PACKING_RANGE: $bad" }
    }
    foreach ($bad in @(-1, 3, 99)) {
        if ($bad -ge 0 -and $bad -le 2) { throw "SELFTEST_HTP_GRAPH_ACTIVATION_FUSION_RANGE: $bad" }
    }
    if (-not (0 -ge 0 -and 0 -le 2) -or -not (2 -ge 0 -and 2 -le 2)) {
        throw 'SELFTEST_HTP_GRAPH_PRECISION_VALID_VALUES'
    }
    $fp16Expected = 'false'
    if ($HtpNativeTensorFp16) { $fp16Expected = 'true' }
    if ($fp16Expected -notin @('true', 'false')) {
        throw 'SELFTEST_HTP_NATIVE_TENSOR_FP16_BOOL'
    }
    Write-Host 'run_nicopedia_htp_generate_self_test=PASS'
    exit 0
}

if ($SelfTest) { Invoke-SelfTest }

if ($Model -ne 'L6' -and $Model -ne 'L19') { throw "MODEL_INVALID: Model must be L6 or L19 (got '$Model')" }
$layers = if ($Model -eq 'L19') { 19 } else { 6 }
if ($Seed -lt 1 -or $Seed -gt 99999) { throw 'SEED_INVALID: Seed must be in 1..99999' }
if ($CheckpointStep -lt 1 -or $CheckpointStep -gt 999999) {
    throw 'CHECKPOINT_STEP_INVALID: CheckpointStep must be in 1..999999'
}
if ($MaxNewBytes -lt 1 -or $MaxNewBytes -gt 1024) { throw 'MAX_NEW_BYTES_INVALID: MaxNewBytes must be in 1..1024' }
if ($Mode -ne 'Greedy' -and $Mode -ne 'Sample') { throw 'MODE_INVALID: Mode must be Greedy or Sample' }
if ($GatePolicy -ne 'legacy' -and $GatePolicy -ne 'candidate') { throw 'GATE_POLICY_INVALID: GatePolicy must be legacy or candidate' }
if ($GatePolicy -eq 'candidate' -and -not $CandidatePolicyApproved) {
    throw 'CANDIDATE_POLICY_NOT_APPROVED: -GatePolicy candidate requires -CandidatePolicyApproved (independent Reviewer PASS + explicit instruction)'
}
if ($HtpGraphPrecisionMode -lt 0 -or $HtpGraphPrecisionMode -gt 2) {
    throw 'HTP_GRAPH_PRECISION_MODE_INVALID: must be 0, 1 or 2'
}
if ($HtpGraphPrecisionCompensation -lt 0 -or $HtpGraphPrecisionCompensation -gt 2) {
    throw 'HTP_GRAPH_PRECISION_COMPENSATION_INVALID: must be 0, 1 or 2'
}
if ($HtpGraphWeightsPacking -lt 0 -or $HtpGraphWeightsPacking -gt 2) {
    throw 'HTP_GRAPH_WEIGHTS_PACKING_INVALID: must be 0, 1 or 2'
}
if ($HtpGraphAdvancedActivationFusion -lt 0 -or $HtpGraphAdvancedActivationFusion -gt 2) {
    throw 'HTP_GRAPH_ACTIVATION_FUSION_INVALID: must be 0, 1 or 2'
}
if ($Mode -eq 'Sample') {
    if (-not [double]::IsFinite($Temperature) -or $Temperature -le 0.0) { throw 'TEMPERATURE_INVALID' }
    if ($TopK -lt 1 -or $TopK -gt 256) { throw 'TOPK_INVALID' }
}
if ($Prompt -ne '') {
    $promptBytes = [System.Text.Encoding]::UTF8.GetBytes($Prompt)
} elseif ($PromptFile -ne '') {
    $promptFileFull = [IO.Path]::GetFullPath($PromptFile)
    if (-not (Test-Path -LiteralPath $promptFileFull -PathType Leaf)) { throw "PROMPT_FILE_MISSING: $promptFileFull" }
    $promptBytes = [IO.File]::ReadAllBytes($promptFileFull)
} else {
    throw 'PROMPT_REQUIRED: supply -Prompt or -PromptFile'
}
if ($promptBytes.Length -eq 0) { throw 'PROMPT_EMPTY' }
if ($promptBytes.Length -gt 32) {
    Write-Host "prompt=${Model} seed=$Seed bytes=$($promptBytes.Length) -> device uses last 32 bytes (training window semantics)"
}

# Checkpoint + approved anchor (fail-closed before any device work).
# The checkpoint file name embeds the step (htp-seed<S>-l<L>-step<N>.ckpt);
# the device re-validates the step from the file name and the expected
# checkpoint_step intent, so a stale or mismatched file cannot pass.
$checkpoint = Join-Path $trainingRoot "htp-seed$Seed-l$layers-step$CheckpointStep.ckpt"
$anchorFile = Join-Path $trainingRoot "seed$Seed-l$layers-steps$CheckpointStep-result.txt"
if (-not (Test-Path -LiteralPath $checkpoint -PathType Leaf)) { throw "CHECKPOINT_MISSING: $checkpoint" }
if (-not (Test-Path -LiteralPath $anchorFile -PathType Leaf)) { throw "ANCHOR_MISSING: $anchorFile" }
$anchorText = Get-Content -LiteralPath $anchorFile -Raw
$anchorMatch = [regex]::Match($anchorText, '(?m)^final_parameter_hash=(fnv1a64:[0-9a-f]{16})$')
if (-not $anchorMatch.Success) { throw "ANCHOR_HASH_NOT_FOUND: $anchorFile" }
$anchorHash = $anchorMatch.Groups[1].Value

# Fingerprints computed on the host (never the prompt text itself).
$checkpointSha256 = Get-Sha256Hex $checkpoint
$promptSha256Bytes = [System.Security.Cryptography.SHA256]::Create()
$promptSha256 = [System.BitConverter]::ToString($promptSha256Bytes.ComputeHash($promptBytes)).Replace('-', '').ToLowerInvariant()
Write-Event 'host-staged' @{
    model = $Model; seed = $Seed; checkpoint_step = $CheckpointStep
    prompt_byte_count = $promptBytes.Length
    prompt_truncated = ($promptBytes.Length -gt 32); prompt_sha256 = $promptSha256
    checkpoint_sha256 = $checkpointSha256; anchor_hash = $anchorHash
}

